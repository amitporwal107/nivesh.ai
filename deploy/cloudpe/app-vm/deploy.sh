#!/usr/bin/env bash
#
# deploy.sh — Nivesh app (staging stack) on the CloudPe app VM (cloudpe1).
#
# Runs the existing deploy/nivesh-staging stack with the CloudPe override
# (deploy/cloudpe/app-vm/docker-compose.override.yml). No GCP dependency.
#
# One-time host setup (interactive, needs sudo):
#   sudo bash deploy/cloudpe/app-vm/deploy.sh --setup
#
# Deploy (as the deploy user — this is what GitHub Actions runs; no sudo needed):
#   bash /opt/nivesh-staging/repo/deploy/cloudpe/app-vm/deploy.sh \
#        [--branch=dev] [--backend-only | --frontend-only | --mode=auto --since=<sha>]
#        [--migrate] [--no-sync]
#
# --mode=auto picks backend-only / frontend-only / full from the files changed
# between <sha> and the checked-out HEAD (used by GitHub Actions on push).
#
# Layout (same paths as GCP staging, so the base compose file works unchanged):
#   /opt/nivesh-staging/repo          git checkout (owned by the deploy user)
#   /opt/nivesh-staging/.env.staging  generated by bootstrap-staging.sh (mode 600)
#   /opt/nivesh-staging/data/...      Postgres / Mongo / Redis volumes
#   /opt/nivesh/ssl/{cert,key}.pem    TLS for the edge nginx (self-signed until a
#                                     Cloudflare Origin cert is installed)

set -euo pipefail

STAGING_ROOT=/opt/nivesh-staging
REPO_DIR="$STAGING_ROOT/repo"
ENV_FILE="$STAGING_ROOT/.env.staging"
REPO_URL="${REPO_URL:-git@github.com:amitporwal107/nivesh.ai.git}"
BASE_COMPOSE="$REPO_DIR/deploy/nivesh-staging/docker-compose.staging.yml"
OVERRIDE_COMPOSE="$REPO_DIR/deploy/cloudpe/app-vm/docker-compose.override.yml"
SSL_DIR=/opt/nivesh/ssl
MIN_FREE_MB="${MIN_FREE_MB:-4000}"

BRANCH=dev
MODE=full
SINCE=
MIGRATE=false
SYNC=true
SETUP=false

for arg in "$@"; do
  case "$arg" in
    --setup)          SETUP=true ;;
    --backend-only)   MODE=backend ;;
    --frontend-only)  MODE=frontend ;;
    --mode=auto)      MODE=auto ;;
    --since=*)        SINCE="${arg#--since=}" ;;
    --migrate)        MIGRATE=true ;;
    --no-sync)        SYNC=false ;;
    --branch=*)       BRANCH="${arg#--branch=}" ;;
    -h|--help)        sed -n '2,22p' "$0"; exit 0 ;;
    *)                echo "Unknown argument: $arg" >&2; exit 2 ;;
  esac
done

log()  { printf '\033[1;36m[cloudpe-app]\033[0m %s\n' "$*"; }
ok()   { printf '\033[1;32m[cloudpe-app]\033[0m %s\n' "$*"; }
fail() { printf '\033[1;31m[cloudpe-app] FATAL:\033[0m %s\n' "$*" >&2; exit 1; }

# ── One-time setup (root) ─────────────────────────────────────────────────────
if [[ "$SETUP" == "true" ]]; then
  [[ $EUID -eq 0 ]] || fail "--setup must run with sudo."
  DEPLOY_USER="${SUDO_USER:-}"
  [[ -n "$DEPLOY_USER" && "$DEPLOY_USER" != "root" ]] || fail "Run --setup via sudo from the deploy user."

  if ! command -v docker >/dev/null 2>&1; then
    log "Installing Docker Engine + Compose plugin (get.docker.com)..."
    curl -fsSL https://get.docker.com | sh
  fi
  systemctl enable --now docker
  usermod -aG docker "$DEPLOY_USER"
  apt-get update -qq
  apt-get install -y -qq git curl openssl jq >/dev/null

  mkdir -p "$STAGING_ROOT"
  chown "$DEPLOY_USER:$DEPLOY_USER" "$STAGING_ROOT"
  if [[ ! -d "$REPO_DIR/.git" ]]; then
    log "Cloning $BRANCH into $REPO_DIR as $DEPLOY_USER..."
    sudo -H -u "$DEPLOY_USER" git clone --branch "$BRANCH" "$REPO_URL" "$REPO_DIR"
  fi

  # Data dirs + .env.staging with fresh random DB passwords (existing file is kept).
  bash "$REPO_DIR/deploy/nivesh-staging/bootstrap-staging.sh"
  # The deploy user runs compose, so it must be able to read the env file.
  chown "$DEPLOY_USER:$DEPLOY_USER" "$ENV_FILE"
  chmod 600 "$ENV_FILE"

  if [[ ! -f "$SSL_DIR/cert.pem" ]]; then
    log "No TLS cert at $SSL_DIR — creating a self-signed one (replace with a Cloudflare Origin cert)."
    mkdir -p "$SSL_DIR"
    openssl req -x509 -nodes -newkey rsa:2048 -days 365 \
      -subj "/CN=staging.niveshcopilot.com" \
      -keyout "$SSL_DIR/key.pem" -out "$SSL_DIR/cert.pem" 2>/dev/null
    chmod 600 "$SSL_DIR/key.pem"
  fi

  ok "Setup done. Log out and back in (docker group), then run without --setup to deploy."
  exit 0
fi

# ── Deploy (deploy user) ──────────────────────────────────────────────────────
[[ $EUID -ne 0 ]] || fail "Deploy as the deploy user, not root (use --setup for root steps)."
docker info >/dev/null 2>&1 || fail "Cannot reach Docker as $(id -un). Run --setup, then log in again."
[[ -f "$ENV_FILE" ]] || fail "Missing $ENV_FILE. Run: sudo bash $0 --setup"
[[ -r "$ENV_FILE" ]] || fail "$ENV_FILE is not readable by $(id -un)."
[[ -f "$SSL_DIR/cert.pem" ]] || fail "Missing $SSL_DIR/cert.pem. Run: sudo bash $0 --setup"

log "Branch=$BRANCH mode=$MODE migrate=$MIGRATE"

# Disk precheck: a full build writes several GB.
FREE_MB=$(df -Pm / | awk 'NR==2{print $4}')
if (( FREE_MB < MIN_FREE_MB )); then
  log "Only ${FREE_MB}MB free — pruning build cache and dangling images..."
  docker builder prune -af >/dev/null 2>&1 || true
  docker image prune -f >/dev/null 2>&1 || true
  FREE_MB=$(df -Pm / | awk 'NR==2{print $4}')
  (( FREE_MB >= MIN_FREE_MB )) || fail "Only ${FREE_MB}MB free on / (need ${MIN_FREE_MB}MB)."
fi
log "Disk: ${FREE_MB}MB free"

if [[ "$SYNC" == "true" ]]; then
  log "Syncing $REPO_DIR to origin/$BRANCH..."
  git -C "$REPO_DIR" fetch --quiet origin "$BRANCH"
  git -C "$REPO_DIR" checkout --quiet "$BRANCH"
  git -C "$REPO_DIR" reset --hard --quiet "origin/$BRANCH"
fi
log "Code: $(git -C "$REPO_DIR" log -1 --oneline)"
if [[ "$MODE" == "auto" ]]; then
  MODE=full
  if [[ -n "$SINCE" ]] && git -C "$REPO_DIR" cat-file -e "$SINCE^{commit}" 2>/dev/null; then
    CHANGED=$(git -C "$REPO_DIR" diff --name-only "$SINCE" HEAD)
    BE=$( { grep -E '^backend/' <<<"$CHANGED" | grep -vE '^backend/nidp/' || true
            grep -E '^backend/nidp/services/copilot_agent/|^deploy/nivesh-app/Dockerfile\.backend' <<<"$CHANGED" || true; } )
    FE=$(grep -E '^(frontend|frontend-v5)/|^deploy/nivesh-app/Dockerfile\.frontend|^deploy/nivesh-staging/app-frontend-nginx\.conf$' <<<"$CHANGED" || true)
    STACK=$(grep -E '^deploy/(nivesh-staging|cloudpe/app-vm)/' <<<"$CHANGED" | grep -v 'app-frontend-nginx.conf' || true)
    if [[ -z "$STACK" && -n "$BE" && -z "$FE" ]]; then MODE=backend
    elif [[ -z "$STACK" && -z "$BE" && -n "$FE" ]]; then MODE=frontend
    fi
  fi
  log "Auto mode since ${SINCE:-<none>} -> $MODE"
fi
[[ -f "$OVERRIDE_COMPOSE" ]] || fail "Missing $OVERRIDE_COMPOSE on $BRANCH — merge deploy/cloudpe into it first."

# Docker network MTU must match the host NIC (base file pins GCP's 1460).
DEFAULT_IF=$(ip route show default | awk '{print $5; exit}')
export CLOUDPE_MTU
CLOUDPE_MTU=$(cat "/sys/class/net/$DEFAULT_IF/mtu")
log "Host MTU ($DEFAULT_IF): $CLOUDPE_MTU"

# The base file joins an external network created by the GCP prod stack.
docker network inspect nidp-bridge >/dev/null 2>&1 || docker network create nidp-bridge >/dev/null

COMPOSE=(docker compose --env-file "$ENV_FILE" -f "$BASE_COMPOSE" -f "$OVERRIDE_COMPOSE")
"${COMPOSE[@]}" config -q

case "$MODE" in
  full)
    "${COMPOSE[@]}" build --pull
    "${COMPOSE[@]}" up -d --remove-orphans
    ;;
  backend)
    "${COMPOSE[@]}" build --pull app-backend
    "${COMPOSE[@]}" up -d --force-recreate app-backend
    ;;
  frontend)
    "${COMPOSE[@]}" build --pull app-frontend app-frontend-v5
    "${COMPOSE[@]}" up -d --force-recreate --remove-orphans app-frontend app-frontend-v5
    ;;
esac

if [[ "$MIGRATE" == "true" ]]; then
  log "Running Postgres migrations (app-migrate)..."
  "${COMPOSE[@]}" --profile migrate run --rm app-migrate
fi

docker builder prune -af >/dev/null 2>&1 || log "WARN: builder prune failed (continuing)"

if [[ "$MODE" != "frontend" ]]; then
  log "Waiting for nivesh-staging-app-backend to be healthy..."
  for _ in $(seq 1 60); do
    [[ "$(docker inspect --format '{{.State.Health.Status}}' nivesh-staging-app-backend 2>/dev/null)" == "healthy" ]] && break
    sleep 5
  done
  [[ "$(docker inspect --format '{{.State.Health.Status}}' nivesh-staging-app-backend 2>/dev/null)" == "healthy" ]] || {
    docker logs --tail 40 nivesh-staging-app-backend 2>&1 || true
    fail "nivesh-staging-app-backend did not become healthy."
  }
fi

if docker ps --format '{{.Names}}' | grep -qx nivesh-staging-nginx; then
  docker exec nivesh-staging-nginx nginx -t >/dev/null 2>&1 \
    && docker exec nivesh-staging-nginx nginx -s reload >/dev/null \
    || "${COMPOSE[@]}" up -d --force-recreate nginx
fi

# Smoke checks through the edge nginx on loopback (the real request path).
PORT=$(grep -E '^PI_NGINX_PORT=' "$ENV_FILE" | cut -d= -f2 || true); PORT="${PORT:-8443}"
RESOLVE=(--resolve "staging.niveshcopilot.com:$PORT:127.0.0.1")
BASE_URL="https://staging.niveshcopilot.com:$PORT"
FAILED=0
for path in /api/healthz /v2/ /v5/; do
  code=000
  for _ in $(seq 1 10); do
    code=$(curl -sk -o /dev/null -w '%{http_code}' --max-time 10 "${RESOLVE[@]}" "$BASE_URL$path" || true)
    [[ "$code" == "200" ]] && break
    sleep 3
  done
  echo "  $path -> HTTP $code"
  [[ "$code" == "200" ]] || FAILED=1
done
echo "  healthz body: $(curl -sk --max-time 10 "${RESOLVE[@]}" "$BASE_URL/api/healthz" | head -c 300)"

"${COMPOSE[@]}" ps --format 'table {{.Name}}\t{{.Status}}'
(( FAILED == 0 )) || fail "Smoke checks failed."
ok "App deploy complete: $(git -C "$REPO_DIR" log -1 --oneline)"
