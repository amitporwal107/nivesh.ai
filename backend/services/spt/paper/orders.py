logger = logging.getLogger(__name__)

ENTRY_OK_OUTCOMES = ("allow", "reduce")
ENTRY_OK_DECISIONS = (C.RISK_APPROVE, C.RISK_APPROVE_REDUCED, C.RISK_CONDITIONAL)
EXIT_REASONS = ("stop", "target_1", "target_2", "trailing", "trend", "time", "manual", "risk_action", "expiry")
TERMINAL = (C.ORD_FILLED, C.ORD_CANCELLED, C.ORD_EXPIRED, C.ORD_REJECTED)
MAX_RETRIES = 4


class ExitRefused(RuntimeError):
    """An exit order cannot be created: `code` is the stable reason (position_not_open, nothing_to_exit, ...)."""

    def __init__(self, code: str, message: str = "") -> None:
        super().__init__(message or code)
        self.code = code


def _f(x: Any) -> Optional[float]:
    return execution._num(x)


def _whole(x: Any) -> Optional[int]:
    if isinstance(x, bool):
        return None
    try:
        f = float(x)
    except (TypeError, ValueError):
        return None
    return int(f) if f >= 1 and f == int(f) else None


def _sum_costs(rows: List[Dict[str, float]]) -> Dict[str, float]:
    if not rows:
        return {k: 0.0 for k in (*cost_card.COMPONENTS, "total")}
    return cost_card.add(*rows)


async def _emit(db, order: Dict[str, Any], event_type: str, key: str, payload: Dict[str, Any],
                now: Optional[datetime] = None) -> None:
    await ev.emit(db, event_type, idempotency_key=key, source_service=store.SOURCE, payload=payload,
                  occurred_at=store.iso(now), correlation_id=order.get("correlation_id"), account_id=order.get("user_id"),
                  instrument_id=order.get("symbol"))


def _order_payload(order: Dict[str, Any], **extra: Any) -> Dict[str, Any]:
    return {"order_id": order["_id"], "purpose": order.get("purpose"), "symbol": order.get("symbol"),
            "side": order.get("side"), "order_type": order.get("order_type"), "quantity": order.get("quantity"),
            "filled_quantity": order.get("filled_quantity"), "remaining_quantity": order.get("remaining_quantity"),
            "state": order.get("state"), "proposal_id": order.get("proposal_id"), "position_id": order.get("position_id"),
            "reason": order.get("reason"), "execution_version": C.EXECUTION_VERSION, **extra}


# ── entry orders (slice B → here, DESIGN §4) ─────────────────────────────────────────────────────────────────────────

def _validate_entry(order: Dict[str, Any], risk_decision: Dict[str, Any], now: datetime) -> Optional[str]:
    """The first reason this ENTRY cannot be queued, or None. Pure."""
    rd = risk_decision or {}
    decision = rd.get("decision")
    outcome = rd.get("outcome")
    if not rd.get("reservation_id"):
        return "risk_not_approved"
    if not (outcome in ENTRY_OK_OUTCOMES or decision in ENTRY_OK_DECISIONS):
        return "risk_not_approved"
    if not order["symbol"]:
        return "symbol_missing"
    if order["side"] != "BUY":
        return "direction_not_enabled"                       # DESIGN D5: long cash equity tonight
    if order["order_type"] not in C.ORDER_TYPES:
        return "order_type_invalid"
    if order["quantity"] is None:
        return "quantity_invalid"
    approved = rd.get("approved_qty")
    if approved is not None and _whole(approved) is not None and order["quantity"] > int(approved):
        return "quantity_exceeds_approved"
    if order["order_type"] in ("LIMIT", "SL") and _f(order.get("limit_price")) is None:
        return "limit_price_required"
    if order["order_type"] in ("SL", "SL_M") and _f(order.get("trigger_price")) is None:
        return "trigger_price_required"
    if order["time_in_force"] not in C.TIME_IN_FORCE:
        return "time_in_force_invalid"
    exp = store.parse_ts(order.get("expires_at"))
    if exp is None or exp <= now:
        return "expiry_invalid"
    plan = order.get("exit_plan") or {}
    stop = _f(plan.get("stop_loss"))
    if stop is None:
        return "stop_required"                               # PRD §18 rule 2: every plan has a stop loss
    for key in ("target_1", "target_2"):
        if plan.get(key) is not None and (_f(plan.get(key)) is None or _f(plan.get(key)) <= stop):
            return "target_invalid"
    if _f(plan.get("target_1")) and _f(plan.get("target_2")) and _f(plan["target_2"]) < _f(plan["target_1"]):
        return "target_invalid"
    return None


async def _entry_refusal(db, order: Dict[str, Any], risk_decision: Dict[str, Any], now: datetime) -> Optional[str]:
    """The first reason this ENTRY is refused, or None. FIRST the reservation itself: it must be on the account under
    this order's id (DESIGN §4: order_id = the reservation's trade_id); one that is missing or belongs to another trade
    is marked `not_ours`, so no refusal below can ever release what this order does not hold. Then the pure checks, the
    kill switch / halt / account block, and an open position in the symbol."""
    rid = risk_decision.get("reservation_id")
    if rid:
        account = await db[acct.ACCOUNTS].find_one({"user_id": order["user_id"]}) or {}
        held = [e for e in account.get("reservations") or [] if e.get("id") == rid]
        if not held or held[0].get("trade_id") != order["_id"]:
            await db[store.ORDERS].update_one({"_id": order["_id"]}, {"$set": {"reservation_state": "not_ours"}})
            return "reservation_not_found" if not held else "reservation_trade_mismatch"
    why = _validate_entry(order, risk_decision, now)
    if why is not None:
        return why
    block = await controls.entry_block(db, order["user_id"])
    if block is not None:
        return block["code"]
    if await db[store.POSITIONS].find_one({"user_id": order["user_id"], "symbol": order["symbol"], "direction": "long",
                                           "is_open": True}) is not None:
        return "position_already_open"
    return None


async def create_entry_order(db, *, user_id: str, proposal_id: Optional[str], opportunity_id: Optional[str],
                             risk_decision: Dict[str, Any], symbol: str, side: str, order_type: str, quantity: Any,
                             limit_price: Any, trigger_price: Any, time_in_force: str, expires_at: Any,
                             exit_plan: Dict[str, Any], idempotency_key: str, order_id: str,
                             actor_id: Optional[str] = None, now: Optional[datetime] = None) -> Dict[str, Any]:
    """Create (or return) the paper ENTRY order of an approved proposal. See the module docstring.

    `order_id` must be the `trade_id` slice B passed to risk_gate.service.enter (EntryRequest.store = "spt_orders"), so
    the account's orphan sweep finds this order. Returns the order; `duplicate: true` when it already existed;
    state REJECTED with `reject_reason` when it cannot be queued (its reservation already given back)."""
    if not user_id or not order_id or not idempotency_key:
        raise ValueError("user_id, order_id and idempotency_key are required")
    moment = now or store.utcnow()
    await store.ensure_indexes(db)
    existing = await db[store.ORDERS].find_one({"$or": [{"_id": order_id}, {"idempotency_key": idempotency_key}]})
    if existing is not None:
        return {**existing, "duplicate": True}
    rd = dict(risk_decision or {})
    tif = str(time_in_force or "DAY").upper()
    if tif == "DAY":
        session_day = store.session_day_for(moment)
        exp = store.day_close(session_day)
    else:
        exp = store.parse_ts(expires_at)
        session_day = None
    budget = rd.get("budget") or {}
    est = rd.get("estimated_risk_rs") or {}
    corr = rd.get("correlation_id") or proposal_id or order_id
    doc: Dict[str, Any] = {
        "_id": order_id, "user_id": user_id, "account_id": user_id, "proposal_id": proposal_id,
        "opportunity_id": opportunity_id, "purpose": "ENTRY", "position_id": None,
        "symbol": str(symbol or "").strip().upper(), "exchange": "NSE", "side": str(side or "").upper(),
        "direction": "long", "order_type": str(order_type or "").upper(), "quantity": _whole(quantity),
        "filled_quantity": 0, "remaining_quantity": _whole(quantity) or 0, "cancelled_quantity": 0,
        "limit_price": _f(limit_price), "trigger_price": _f(trigger_price), "triggered_at": None,
        "time_in_force": tif, "session_day": session_day.isoformat() if session_day else None,
        "expires_at": store.iso(exp) if exp else None, "state": C.ORD_CREATED,
        "risk": {"decision_id": rd.get("decision_id"), "reservation_id": rd.get("reservation_id"),
                 "decision": rd.get("decision") or rd.get("outcome"), "outcome": rd.get("outcome"),
                 "funding_rs": _f(budget.get("funding_rs")), "risk_rs": _f(est.get("total")),
                 "approved_qty": rd.get("approved_qty"), "policy_version": rd.get("policy_version"),
                 "limits_version": rd.get("limits_version"), "sector": rd.get("sector")},
        "planned_entry_price": _f(rd.get("planned_entry_price")) or _f(limit_price),
        "exit_plan": dict(exit_plan or {}), "idempotency_key": idempotency_key, "correlation_id": corr,
        "reason": None, "exit_full": None, "gap": False, "trigger": None,
        "cost_model": execution.card_snapshot(), "costs": _sum_costs([]), "avg_fill_price": None,
        "fills": [], "fills_seq": 0, "logged_seq": 0, "position_seq": 0,
        "attempts": [], "attempt_count": 0, "last_attempt": None, "last_quote_at": None,
        "reservation_state": "held" if rd.get("reservation_id") else "none",
        "reject_reason": None, "cancel_reason": None, "terminal_done": False,
        "execution_version": C.EXECUTION_VERSION, "actor_id": actor_id or user_id,
        "created_at": store.iso(moment), "updated_at": store.iso(moment), "version": 0,
    }
    try:
        await db[store.ORDERS].insert_one(doc)
    except DuplicateKeyError:
        first = await db[store.ORDERS].find_one({"$or": [{"_id": order_id}, {"idempotency_key": idempotency_key}]})
        if first is not None:
            return {**first, "duplicate": True}
        raise
    await _emit(db, doc, "PAPER_ORDER_CREATED", f"order:{order_id}:created", _order_payload(doc), moment)
    why = await _entry_refusal(db, doc, rd, moment)
    if why is not None:
        return await reject(db, order_id, why, now=moment) or doc
    v = await store.transition(db, store.ORDERS, order_id, expect_states=[C.ORD_CREATED], expect_version=0,
                               to_state=C.ORD_VALIDATED, now=moment)
    if v is None:
        return await store.get_order(db, order_id) or doc
    p = await store.transition(db, store.ORDERS, order_id, expect_states=[C.ORD_VALIDATED], expect_version=v["version"],
                               to_state=C.ORD_PENDING, now=moment)
    return p or await store.get_order(db, order_id) or doc


async def advance_new(db, order: Dict[str, Any], now: datetime) -> Optional[Dict[str, Any]]:
    """Finish an ENTRY left in CREATED / VALIDATED by a process that stopped mid-create: validate again and queue it
    (or reject it). Exits are queued as they are."""
    if order.get("state") not in (C.ORD_CREATED, C.ORD_VALIDATED):
        return order
    if order.get("purpose") == "ENTRY" and order["state"] == C.ORD_CREATED:
        why = await _entry_refusal(db, order, dict(order.get("risk") or {}), now)
        if why is not None:
            return await reject(db, order["_id"], why, now=now)
    cur = order
    if cur["state"] == C.ORD_CREATED:
        cur = await store.transition(db, store.ORDERS, cur["_id"], expect_states=[C.ORD_CREATED],
                                     expect_version=cur["version"], to_state=C.ORD_VALIDATED, now=now)
        if cur is None:
            return await store.get_order(db, order["_id"])
    return await store.transition(db, store.ORDERS, cur["_id"], expect_states=[C.ORD_VALIDATED],
                                  expect_version=cur["version"], to_state=C.ORD_PENDING, now=now)


# ── terminal transitions ─────────────────────────────────────────────────────────────────────────────────────────────

async def _end(db, order_id: str, to_state: str, *, reason: str, field: str, now: Optional[datetime]) -> Optional[Dict[str, Any]]:
    """Move a live order to a terminal state (its remaining quantity cancelled), then run its terminal handling.
    Returns the order after, or None when it was not live."""
    for _ in range(MAX_RETRIES):
        order = await store.get_order(db, order_id)
        if order is None or order.get("state") not in C.ORD_LIVE_STATES:
            return None
        after = await store.transition(
            db, store.ORDERS, order_id, expect_states=C.ORD_LIVE_STATES, expect_version=order["version"],
            to_state=to_state, now=now,
            set_={field: reason, "remaining_quantity": 0,
                  "cancelled_quantity": int(order.get("remaining_quantity") or 0), "ended_at": store.iso(now)})
        if after is not None:
            return await sync_order(db, order_id, now=now)    # fills → position first, then the terminal handling
    logger.warning("spt paper: order %s could not be ended (%s) after %d attempts", order_id, to_state, MAX_RETRIES)
    return None


async def reject(db, order_id: str, reason: str, *, now: Optional[datetime] = None) -> Optional[Dict[str, Any]]:
    return await _end(db, order_id, C.ORD_REJECTED, reason=reason, field="reject_reason", now=now)


async def cancel_paper_order(db, order_id: str, *, reason: str, user_id: Optional[str] = None,
                       now: Optional[datetime] = None) -> Optional[Dict[str, Any]]:
    """Cancel a live order (the user's, when `user_id` is given). None when it is not live (or not the user's)."""
    order = await store.get_order(db, order_id)
    if order is None or (user_id is not None and order.get("user_id") != user_id):
        return None
    return await _end(db, order_id, C.ORD_CANCELLED, reason=reason, field="cancel_reason", now=now)


async def expire_due(db, now: datetime) -> int:
    """Expire every live order whose time in force has passed (DAY: 15:30 IST of its session; GTD: expires_at)."""
    due = await db[store.ORDERS].find({"state": {"$in": list(C.ORD_LIVE_STATES)},
                                       "expires_at": {"$lte": store.iso(now)}}).to_list(5000)
    n = 0
    for order in due:
        if await _end(db, order["_id"], C.ORD_EXPIRED, reason="time_in_force", field="cancel_reason", now=now):
            n += 1
    return n


async def on_terminal(db, order: Dict[str, Any], *, now: Optional[datetime] = None) -> None:
    """What an order's end causes, every step idempotent (so a crash midway is finished by the next sync):
    the reservation of an unfilled ENTRY back (exactly once), the position's exit bookkeeping for an EXIT, the event."""
    state = order.get("state")
    if state not in TERMINAL:
        return
    oid = order["_id"]
    filled = int(order.get("filled_quantity") or 0)
    if order.get("purpose") == "ENTRY":
        rid = (order.get("risk") or {}).get("reservation_id")
        if filled == 0 and rid and order.get("reservation_state") == "held":
            released = await acct.cancel_reservation(db, order["user_id"], rid,
                                                     reason=f"spt order {oid} {state.lower()} with no fill "
                                                            f"({order.get('reject_reason') or order.get('cancel_reason')})")
            await db[store.ORDERS].update_one({"_id": oid, "reservation_state": "held"},
                                              {"$set": {"reservation_state": "released" if released else "not_found",
                                                        "reservation_released_at": store.iso(now)}})
        elif filled > 0 and order.get("reservation_state") == "held":
            await db[store.ORDERS].update_one({"_id": oid, "reservation_state": "held"},
                                              {"$set": {"reservation_state": "kept_for_position"}})
    else:
        from . import positions                                # positions imports this module
        await positions.after_exit_terminal(db, order, now=now)
    if state == C.ORD_CANCELLED:
        await _emit(db, order, "PAPER_ORDER_CANCELLED", f"order:{oid}:cancelled",
                    _order_payload(order, cancel_reason=order.get("cancel_reason")), now)
    elif state == C.ORD_EXPIRED:
        await _emit(db, order, "ORDER_EXPIRED", f"order:{oid}:expired", _order_payload(order), now)
    elif state == C.ORD_REJECTED:
        await _emit(db, order, "PAPER_ORDER_CANCELLED", f"order:{oid}:rejected",
                    _order_payload(order, reject_reason=order.get("reject_reason")), now)
    await db[store.ORDERS].update_one({"_id": oid, "terminal_done": {"$ne": True}}, {"$set": {"terminal_done": True}})


# ── fills ────────────────────────────────────────────────────────────────────────────────────────────────────────────

async def record_attempt(db, order: Dict[str, Any], reason: Optional[str], now: datetime, *,
                         triggered_at: Optional[str] = None, quote: Optional[Dict[str, Any]] = None) -> None:
    """A round that filled nothing: `last_attempt` always, `attempts[]` only when the reason changed (bounded)."""
    att = {"at": store.iso(now), "reason": reason, "quote_at": (quote or {}).get("received_at")}
    update: Dict[str, Any] = {"$set": {"last_attempt": att}, "$inc": {"attempt_count": 1}}
    if (order.get("last_attempt") or {}).get("reason") != reason:
        update["$push"] = {"attempts": att}
    await db[store.ORDERS].update_one({"_id": order["_id"], "state": {"$in": list(C.ORD_LIVE_STATES)}}, update)
    if triggered_at and not order.get("triggered_at"):
        await store.transition(db, store.ORDERS, order["_id"], expect_states=C.ORD_LIVE_STATES,
                               expect_version=order["version"], set_={"triggered_at": triggered_at}, now=now)


async def record_fills(db, order: Dict[str, Any], sim: Dict[str, Any], now: datetime) -> Optional[Dict[str, Any]]:
    """Append this round's fills to the order in ONE conditional update (state, version and the fill count it read).
    None when another writer changed the order first: nothing is recorded and the next round tries again."""
    n = int(order.get("fills_seq") or 0)
    recs: List[Dict[str, Any]] = []
    for i, f in enumerate(sim["fills"], start=1):
        seq = n + i
        value = cost_card.paisa(f["quantity"] * f["price"])
        costs = execution.fill_costs(order["side"], value, first_fill=(seq == 1), model=order.get("cost_model"))
        recs.append({"fill_id": f"{order['_id']}:{seq}", "seq": seq, "quantity": int(f["quantity"]), "price": f["price"],
                     "ref_price": f["ref_price"], "level": f["level"], "depth_unknown": f["depth_unknown"],
                     "basis": f["basis"], "slippage_rs": f["slippage_rs"], "value_rs": value, "costs": costs,
                     "gap": bool(order.get("gap")), "at": store.iso(now), "day": store.ist_day(now).isoformat(),
                     "quote": sim.get("quote")})
    all_fills = list(order.get("fills") or []) + recs
    filled = sum(int(r["quantity"]) for r in all_fills)
    qty = int(order["quantity"])
    value = sum(float(r["value_rs"]) for r in all_fills)
    state = C.ORD_FILLED if filled >= qty else C.ORD_PARTIAL
    fields = {"filled_quantity": filled, "remaining_quantity": max(0, qty - filled),
              "avg_fill_price": round(value / filled, 4) if filled else None,
              "costs": _sum_costs([r["costs"] for r in all_fills]), "fills_seq": n + len(recs),
              "last_quote_at": (sim.get("quote") or {}).get("received_at"),
              "last_attempt": {"at": store.iso(now), "reason": "filled", "quote_at": (sim.get("quote") or {}).get("received_at")}}
    if sim.get("triggered_at") and not order.get("triggered_at"):
        fields["triggered_at"] = sim["triggered_at"]
    if state == C.ORD_FILLED:
        fields["ended_at"] = store.iso(now)
    res = await db[store.ORDERS].update_one(
        {"_id": order["_id"], "state": {"$in": list(C.ORD_LIVE_STATES)}, "version": order["version"], "fills_seq": n},
        {"$push": {"fills": {"$each": recs}}, "$set": {**fields, "state": state, "updated_at": store.iso(now)},
         "$inc": {"version": 1, "attempt_count": 1}})
    if not res.matched_count:
        return None
    return await store.get_order(db, order["_id"])


def fill_doc(order: Dict[str, Any], rec: Dict[str, Any]) -> Dict[str, Any]:
    """One `spt_fills` document from a fill recorded on the order."""
    return {"_id": rec["fill_id"], "order_id": order["_id"], "seq": rec["seq"], "user_id": order["user_id"],
            "purpose": order.get("purpose"), "position_id": order.get("position_id"),
            "entry_order_id": order["_id"] if order.get("purpose") == "ENTRY" else None, "symbol": order.get("symbol"),
            "side": order.get("side"), "reason": order.get("reason"),
            **{k: rec.get(k) for k in ("quantity", "price", "ref_price", "level", "depth_unknown", "basis",
                                       "slippage_rs", "value_rs", "costs", "gap", "at", "day", "quote")},
            "execution_version": C.EXECUTION_VERSION}


async def sync_order(db, order_id: str, *, now: Optional[datetime] = None) -> Optional[Dict[str, Any]]:
    """Propagate an order's recorded fills, each step idempotent and resumable (see the module docstring). Returns the
    order after. Safe to call any number of times: it is how a restarted process catches up."""
    order = await store.get_order(db, order_id)
    if order is None:
        return None
    fills = list(order.get("fills") or [])
    logged = int(order.get("logged_seq") or 0)
    qty = int(order.get("quantity") or 0)
    cum = 0
    for rec in fills:
        cum += int(rec["quantity"])
        if int(rec["seq"]) <= logged:
            continue
        try:
            await db[store.FILLS].insert_one(fill_doc(order, rec))
        except DuplicateKeyError:
            pass                                             # recorded by an earlier pass
        if cum < qty:
            await _emit(db, order, "PAPER_ORDER_PARTIALLY_FILLED", f"order:{order_id}:fill:{rec['seq']}",
                        _order_payload(order, fill={k: rec.get(k) for k in ("seq", "quantity", "price", "basis",
                                                                            "depth_unknown")}, cumulative=cum), now)
    if logged < len(fills):
        if order.get("state") == C.ORD_FILLED:
            await _emit(db, order, "PAPER_ORDER_FILLED", f"order:{order_id}:filled",
                        _order_payload(order, avg_fill_price=order.get("avg_fill_price")), now)
        # only after the fill documents and their events: a crash before this line redoes them (both idempotent)
        await db[store.ORDERS].update_one({"_id": order_id}, {"$max": {"logged_seq": len(fills)}})
    if int(order.get("position_seq") or 0) < len(fills):
        from . import positions                                # positions imports this module
        await positions.apply_order_fills(db, order, now=now)
        order = await store.get_order(db, order_id) or order
    if order.get("state") in TERMINAL and not order.get("terminal_done"):
        await on_terminal(db, order, now=now)
        order = await store.get_order(db, order_id) or order
    return order


# ── exit orders ──────────────────────────────────────────────────────────────────────────────────────────────────────

FULL_EXIT_REASONS = ("stop", "target_2", "trailing", "trend", "time", "risk_action", "expiry")


async def create_exit_order(db, *, position_id: str, reason: str, quantity: Any = None, order_type: str = "MARKET",
                            limit_price: Any = None, gap: bool = False, trigger: Optional[Dict[str, Any]] = None,
                            actor_id: Optional[str] = None, now: Optional[datetime] = None) -> Dict[str, Any]:
    """A SELL order closing all (quantity None, or ≥ the position) or part of an open long position. Raises ExitRefused.

    One live exit per position: a second request for the same reason returns the live one; a full exit replaces a live
    partial one (it is cancelled first); a partial request while another exit is live is refused (`exit_order_live`).
    A full exit also cancels the remainder of a live ENTRY of the position, so the position stops growing. Exits are
    never blocked by the kill switch (PRD §18 rules 12–14)."""
    if reason not in EXIT_REASONS:
        raise ExitRefused("exit_reason_invalid")
    otype = str(order_type or "MARKET").upper()
    if otype not in ("MARKET", "LIMIT"):
        raise ExitRefused("order_type_invalid")
    lim = _f(limit_price)
    if otype == "LIMIT" and lim is None:
        raise ExitRefused("limit_price_required")
    moment = now or store.utcnow()
    await store.ensure_indexes(db)
    for _ in range(MAX_RETRIES):
        pos = await store.get_position(db, position_id)
        if pos is None or pos.get("state") not in C.POS_OPEN_STATES:
            raise ExitRefused("position_not_open")
        held = int(pos.get("quantity") or 0)
        if held <= 0:
            raise ExitRefused("nothing_to_exit")
        want = None if quantity is None else _whole(quantity)
        if quantity is not None and want is None:
            raise ExitRefused("quantity_invalid")
        full = want is None or want >= held or reason in FULL_EXIT_REASONS
        qty = held if full else want
        live_id = pos.get("live_exit_order_id")
        if live_id:
            live = await store.get_order(db, live_id)
            if live is None:
                return await ensure_exit_order(db, pos, now=moment)
            if live.get("state") in C.ORD_LIVE_STATES:
                if live.get("exit_full") or (not full and live.get("reason") == reason):
                    return {**live, "duplicate": True}
                if not full:
                    raise ExitRefused("exit_order_live")
                await cancel_paper_order(db, live_id, reason="replaced_by_full_exit", now=moment)
                continue                                    # re-read the position after the cancel
        if full:
            entry = await store.get_order(db, pos.get("entry_order_id"))
            if entry is not None and entry.get("state") in C.ORD_LIVE_STATES:
                await cancel_paper_order(db, entry["_id"], reason="exit_started", now=moment)
                continue
        new_id = str(uuid.uuid4())
        seq = int(pos.get("exit_seq") or 0) + 1
        claim = {"live_exit_order_id": new_id, "live_exit_reason": reason, "live_exit_qty": qty, "live_exit_full": full,
                 "live_exit_type": otype, "live_exit_limit": lim, "live_exit_gap": bool(gap), "live_exit_trigger": trigger,
                 "live_exit_actor": actor_id, "exit_seq": seq}
        to_state = C.POS_CLOSING if full else None
        after = await store.transition(db, store.POSITIONS, position_id, expect_states=C.POS_OPEN_STATES,
                                       expect_version=pos["version"], to_state=to_state, set_=claim, now=moment)
        if after is None:
            continue
        return await ensure_exit_order(db, after, now=moment)
    raise ExitRefused("position_changed")


async def ensure_exit_order(db, pos: Dict[str, Any], *, now: Optional[datetime] = None) -> Dict[str, Any]:
    """Write the exit order the position has claimed (`live_exit_order_id`), or return it when it exists. Also the
    recovery of a process that stopped between the claim and the insert."""
    oid = pos["live_exit_order_id"]
    have = await store.get_order(db, oid)
    if have is not None:
        return have
    moment = now or store.utcnow()
    qty = int(pos.get("live_exit_qty") or pos.get("quantity") or 0)
    doc: Dict[str, Any] = {
        "_id": oid, "user_id": pos["user_id"], "account_id": pos["user_id"], "proposal_id": pos.get("proposal_id"),
        "opportunity_id": pos.get("opportunity_id"), "purpose": "EXIT", "position_id": pos["_id"],
        "entry_order_id": pos.get("entry_order_id"), "symbol": pos["symbol"], "exchange": "NSE", "side": "SELL",
        "direction": "long", "order_type": pos.get("live_exit_type") or "MARKET", "quantity": qty, "filled_quantity": 0,
        "remaining_quantity": qty, "cancelled_quantity": 0, "limit_price": pos.get("live_exit_limit"),
        "trigger_price": None, "triggered_at": None, "time_in_force": "DAY",
        "session_day": store.session_day_for(moment).isoformat(),
        "expires_at": store.iso(store.day_close(store.session_day_for(moment))), "state": C.ORD_CREATED,
        "risk": None, "planned_entry_price": None, "exit_plan": None,
        "idempotency_key": f"exit:{pos['_id']}:{int(pos.get('exit_seq') or 1)}", "correlation_id": pos.get("correlation_id"),
        "reason": pos.get("live_exit_reason"), "exit_full": bool(pos.get("live_exit_full")),
        "gap": bool(pos.get("live_exit_gap")), "trigger": pos.get("live_exit_trigger"),
        "cost_model": execution.card_snapshot(), "costs": _sum_costs([]), "avg_fill_price": None,
        "fills": [], "fills_seq": 0, "logged_seq": 0, "position_seq": 0, "attempts": [], "attempt_count": 0,
        "last_attempt": None, "last_quote_at": None, "reservation_state": "none", "reject_reason": None,
        "cancel_reason": None, "terminal_done": False, "execution_version": C.EXECUTION_VERSION,
        "actor_id": pos.get("live_exit_actor") or "spt-monitor", "created_at": store.iso(moment),
        "updated_at": store.iso(moment), "version": 0,
    }
    try:
        await db[store.ORDERS].insert_one(doc)
    except DuplicateKeyError:
        return await store.get_order(db, oid) or doc
    await _emit(db, doc, "PAPER_ORDER_CREATED", f"order:{oid}:created", _order_payload(doc, trigger=doc["trigger"]), moment)
    v = await store.transition(db, store.ORDERS, oid, expect_states=[C.ORD_CREATED], expect_version=0,
                               to_state=C.ORD_VALIDATED, now=moment)
    if v is None:
        return await store.get_order(db, oid) or doc
    return await store.transition(db, store.ORDERS, oid, expect_states=[C.ORD_VALIDATED], expect_version=v["version"],
                                  to_state=C.ORD_PENDING, now=moment) or await store.get_order(db, oid) or doc


def public(order: Dict[str, Any], *, with_fills: bool = False) -> Dict[str, Any]:
    """The order as the API shows it to its owner."""
    out = {k: v for k, v in order.items() if k not in ("fills", "logged_seq", "position_seq", "terminal_done")}
    out["order_id"] = order["_id"]
    if with_fills:
        out["fills"] = list(order.get("fills") or [])
    return out
