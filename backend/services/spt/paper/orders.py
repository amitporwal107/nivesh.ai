"""Paper orders (DESIGN.md §3 `spt_orders`, §4 the call from slice B, §5 the order state machine; WF §12).

STATE MACHINE (constants.ORD_*): CREATED → VALIDATED → PENDING → PARTIALLY_FILLED → FILLED, and CANCELLED / EXPIRED /
REJECTED from any live state. Every transition is ONE conditional update on (state, version) (store.transition).

IDEMPOTENCY. `_id` = the order id (for an ENTRY, the risk reservation's `trade_id`, generated by slice B) and a unique
`idempotency_key`. A second create with the same key (or id) inserts nothing and returns the first order with
`duplicate: true`. Exit orders are keyed `exit:<position_id>:<n>`, n counted on the position, and a position holds at most
one live exit order (`live_exit_order_id`).

FILLS ARE RECORDED ON THE ORDER ATOMICALLY. `record_fills` appends the round's fills (seq n+1…) to `order.fills` in the
SAME conditional update that advances filled/remaining quantity, state and version. So a cancel that read the order
before the fill matches nothing, and a cancel after it sees the fill (and keeps the reservation for the position).
`sync_order` then propagates them, each step idempotent and resumable after a crash:
    order.fills → spt_fills (unique (order_id, seq); `logged_seq`) → events (stable keys) → the position
    (positions.apply_order_fills; `position_seq`) → terminal handling once (`terminal_done`).

RESERVATIONS (services/paper_account). An ENTRY carries the risk decision of slice B's `risk_gate.service.enter`, whose
reservation (`reservation_id`, trade_id = this order id, store "spt_orders") blocked the funding and the risk.
  * An ENTRY that ends with NO fill (rejected, cancelled, expired) gives it back with
    `paper_account.cancel_reservation(reservation_id)` — what `risk_gate.service.release_unused` calls, called directly so
    this module does not import the whole risk service. It is conditional on the reservation still being on the account,
    so it releases exactly once however often it is called.
  * An ENTRY that filled partly and then ends (cancel / expiry): the remaining quantity is cancelled and the WHOLE
    reservation is KEPT for the open position (conservative: the account stays blocked for the full planned size until
    the position closes); positions.py releases it then with `paper_account.release(...)`.

A business refusal never raises: `create_entry_order` returns the order REJECTED with `reject_reason`, its reservation
already given back. Only a programming error (no user, no id, no key) raises ValueError, before anything is written.
"""
from __future__ import annotations

