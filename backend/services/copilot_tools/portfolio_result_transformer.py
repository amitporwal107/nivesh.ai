"""portfolio_result_transformer — turn a sleeve_builder result into the
unified insight_card envelope(s) the copilot chat renders (Doc 06 §6.8,
"every response, same chrome").

This is the backend seam for plan Steps 10-13: the design-engineer
identified `insight_card_transformers.py` as the integration point, and
this module is its portfolio-builder sibling. It maps the engine output of
`services.sleeve_builder.build_sleeve_portfolio` onto the same
`InsightCardData` sections that every other tool uses, so the proposal
renders with identical chrome.

Two honest output modes, driven by the engine's own compliance flags —
never re-decided here:

  • Category / model mode — when Compliance has NOT enabled named-scheme
    output (`compliance.names_allowed` is False) OR a sleeve has no funds.
    Output is allocation + category-level guidance with the governed
    disclaimer and ZERO scheme names. This is the regulatory default.

  • Named mode — when names are allowed AND there is at least one named
    pick. Output is a header card (allocation rollup + validation verdict)
    + one card per sleeve listing each pick as STRUCTURED fields (score,
    gate chips, overlap note). A sleeve that ends up empty after gates is
    surfaced explicitly with its reason — never silently dropped.

Engine-vs-narration boundary (PRD honesty contract): every pick's name,
score and gate status live in structured `InsightFinding` / `InsightKpi`
fields built from engine rows. They are NEVER concatenated into a
free-text recommendation string, so a hallucinated scheme name cannot
appear without a corresponding engine row.

Gate severity mapping (per UX feasibility — a not_evaluated gate must be
visually distinct, NOT shown as a pass):
  • passed        -> "healthy"  (green)
  • failed        -> "critical" (red)
  • not_evaluated -> "medium"   (amber) — explicitly "not checked", never green

The disclosures block is mandatory and non-dismissible: it is attached to
every result (both modes) as a dedicated card so past-performance,
market-risk, model-driven and conflict-of-interest notices always ride
along with the proposal.
"""
from __future__ import annotations

from datetime import datetime, timezone
from typing import Any, Dict, List, Optional

from models_copilot_widgets import (
    WidgetEnvelope,
    FreshnessChip,
    AgentInfo,
    InsightCardData,
    InsightHero,
    InsightKpi,
    InsightFinding,
    InsightRecommendation,
    InsightEducation,
    InsightSeverity,
)

_AGENT = AgentInfo(id="portfolio_builder", label="Portfolio Builder", version="v1")

# Mandatory regulatory disclosures — shown on every result, non-dismissible.
# These are SEBI/AMFI-style notices a model-driven proposal must carry.
DISCLOSURES: List[str] = [
    "Past performance is not indicative of future returns.",
    "Mutual fund investments are subject to market risks; read all "
    "scheme-related documents carefully.",
    "This proposal is model-driven and generated by an automated allocation "
    "engine — it is not personalised investment advice.",
    "Conflict-of-interest: where a regular plan is shown, the distributor may "
    "earn a commission. Verify costs before investing.",
]

# Engine gate status -> card severity. A not_evaluated gate is amber/medium,
# deliberately NOT "healthy" — it means "could not be checked", never "passed".
_GATE_SEVERITY: Dict[str, InsightSeverity] = {
    "passed": "healthy",
    "failed": "critical",
    "not_evaluated": "medium",
}

_GATE_VERB: Dict[str, str] = {
    "passed": "OK",
    "failed": "FAILED",
    "not_evaluated": "not checked",
}


def _iso_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _freshness() -> FreshnessChip:
    # A proposal is computed live from the governed policy; it is not a
    # cached market quote. State "live" with no external source.
    return FreshnessChip(state="live", last_updated=_iso_now(), source=["allocation_policy"])


def _envelope(title: str, card: InsightCardData, *, suggestions: Optional[List[str]] = None) -> Dict[str, Any]:
    """Wrap an InsightCardData in the standard WidgetEnvelope dict.

    Returns model_dump() so the result is a plain serialisable dict, matching
    every other widget endpoint (routes/copilot_widgets.py).
    """
    env = WidgetEnvelope(
        kind="insight_card",
        title=title,
        freshness=_freshness(),
        agent=_AGENT,
        data=card.model_dump(),
        suggestions=suggestions or [],
    )
    return env.model_dump()


def _fund_score(fund: Dict[str, Any]) -> Optional[float]:
    """A fund carries quality_score (equity) or debt_score (debt). Return
    whichever is present, without inventing a value."""
    for k in ("quality_score", "debt_score", "composite_100", "composite_score"):
        v = fund.get(k)
        if v is not None:
            return float(v)
    return None


def _fund_name(fund: Dict[str, Any]) -> str:
    return str(fund.get("scheme_name") or fund.get("isin") or "Fund")


def _gate_summary(gate_results: Optional[List[Dict[str, Any]]]) -> Dict[str, Any]:
    """Reduce a fund's gate_results list to counts + the worst severity, so a
    not_evaluated gate is surfaced distinctly and never collapses into a pass.

    Returns {worst_severity, passed, failed, not_evaluated, chips:[...]} where
    each chip is {gate, status, severity, reason}.
    """
    gates = gate_results or []
    chips: List[Dict[str, Any]] = []
    counts = {"passed": 0, "failed": 0, "not_evaluated": 0}
    for g in gates:
        status = str(g.get("status") or "not_evaluated")
        if status not in counts:
            # Unknown status is treated as not_evaluated, never a pass.
            status = "not_evaluated"
        counts[status] += 1
        chips.append({
            "gate": g.get("gate"),
            "status": status,
            "severity": _GATE_SEVERITY[status],
            "reason": g.get("reason"),
        })
    # Worst severity drives the finding priority. failed > not_evaluated > passed.
    if counts["failed"]:
        worst: InsightSeverity = "critical"
    elif counts["not_evaluated"]:
        worst = "medium"
    elif counts["passed"]:
        worst = "healthy"
    else:
        # No gates evaluated at all — surface as not-checked, not as healthy.
        worst = "medium"
    return {"worst_severity": worst, "chips": chips, **counts}


def _overlap_note(fund: Dict[str, Any]) -> str:
    """Human-readable overlap note built ONLY from engine fields."""
    status = str(fund.get("overlap_status") or "not_evaluated")
    pct = fund.get("overlap_pct")
    if status == "evaluated":
        if pct is not None:
            return f"Overlap checked · max {float(pct) * 100:.0f}% vs siblings"
        return "Overlap checked"
    if status == "rejected":
        if pct is not None:
            return f"Overlap too high ({float(pct) * 100:.0f}%)"
        return "Overlap too high"
    return "Overlap not evaluated (no holdings data)"


def _priority_from_severity(sev: InsightSeverity) -> str:
    if sev in ("critical", "high"):
        return "high"
    if sev == "medium":
        return "medium"
    return "low"


# ── Mode A — category / model guidance (NO scheme names) ────────────────────

def _category_card(builder_output: Dict[str, Any]) -> Dict[str, Any]:
    """Allocation + category-level guidance card. Emits ZERO scheme names.

    Used when Compliance has not enabled named output, or any sleeve is empty.
    The governed disclaimer (from the engine) is shown verbatim.
    """
    alloc = builder_output.get("allocation") or {}
    sleeves = builder_output.get("sleeves") or []
    compliance = builder_output.get("compliance") or {}
    profile = builder_output.get("risk_profile") or "moderate"
    horizon = builder_output.get("horizon_years")

    eq = float(alloc.get("equity", 0) or 0)
    hero = InsightHero(
        severity="info",
        eyebrow="Model portfolio",
        headline=f"{str(profile).title()} allocation model",
        primary_value=f"{eq:.0f}%",
        primary_label="equity allocation",
        subtitle=(
            "Category-level guidance — specific scheme names are not shown in "
            "this mode."
        ),
    )

    kpis: List[InsightKpi] = []
    for ac in ("equity", "debt", "gold", "cash"):
        pct = float(alloc.get(ac, 0) or 0)
        if pct <= 0:
            continue
        kpis.append(InsightKpi(label=ac.title(), value=f"{pct:.0f}%"))
    if horizon is not None:
        kpis.append(InsightKpi(label="Horizon", value=f"{float(horizon):.0f} yr"))

    # Findings = the governed sub-sleeve model at CATEGORY granularity only.
    findings: List[InsightFinding] = []
    for s in sleeves:
        members = s.get("category_members") or []
        detail = ", ".join(members) if members else (s.get("detail") or "")
        findings.append(InsightFinding(
            priority="medium",
            title=f"{s.get('label', 'Sleeve')} · {float(s.get('target_pct', 0)):.0f}%",
            detail=detail,
        ))

    disclaimer = compliance.get("disclaimer") or (
        "This is model and category-level guidance, not a recommendation of "
        "specific schemes or stocks. Mutual funds are subject to market risk."
    )
    recommendation = InsightRecommendation(
        summary=(
            "Here is the allocation model for your profile. Specific fund names "
            "are withheld in category mode."
        ),
        rationale=disclaimer,
    )

    education = InsightEducation(
        heading="Why no fund names?",
        body=(
            "Named scheme recommendations are shown only when compliance has "
            "enabled named-scheme output. Until then, you get the strategic "
            "allocation model and the fund categories to use for each sleeve."
        ),
    )

    card = InsightCardData(
        hero=hero,
        kpis=kpis,
        findings=findings,
        recommendation=recommendation,
        education=education,
    )
    return _envelope("Model portfolio", card,
                     suggestions=["Explain this allocation", "Adjust my risk profile"])


# ── Mode B — named scheme proposal ──────────────────────────────────────────

def _validation_verdict(validation: Optional[Dict[str, Any]]) -> tuple[InsightSeverity, str]:
    """Map the policy-simulation validation block to a severity + label,
    honestly degrading to 'not evaluated' when the sim produced nothing."""
    if not validation:
        return "medium", "Validation not evaluated"
    passed = validation.get("passed")
    if passed is True:
        return "healthy", "Validation passed"
    if passed is False:
        return "high", "Validation flagged"
    # Sim ran but reported no verdict — do not fake a pass.
    return "medium", "Validation inconclusive"


def _header_card(builder_output: Dict[str, Any]) -> Dict[str, Any]:
    """Allocation rollup + validation verdict for the named proposal."""
    alloc = builder_output.get("allocation") or {}
    validation = builder_output.get("validation")
    profile = builder_output.get("risk_profile") or "moderate"
    sleeves = builder_output.get("sleeves") or []
    n_named = sum(len(s.get("funds") or []) for s in sleeves)

    sev, verdict = _validation_verdict(validation)
    eq = float(alloc.get("equity", 0) or 0)

    hero = InsightHero(
        severity=sev,
        eyebrow="Proposed portfolio",
        headline=f"{str(profile).title()} portfolio · {n_named} fund(s)",
        primary_value=f"{eq:.0f}%",
        primary_label="equity allocation",
        subtitle=verdict,
    )

    kpis: List[InsightKpi] = []
    for ac in ("equity", "debt", "gold", "cash"):
        pct = float(alloc.get(ac, 0) or 0)
        if pct <= 0:
            continue
        kpis.append(InsightKpi(label=ac.title(), value=f"{pct:.0f}%"))
    kpis.append(InsightKpi(label="Funds selected", value=str(n_named)))

    # Findings = one line per sleeve (label + target + #picks), structured.
    findings: List[InsightFinding] = []
    for s in sleeves:
        funds = s.get("funds") or []
        if funds:
            findings.append(InsightFinding(
                priority="low",
                title=f"{s.get('label', 'Sleeve')} · {float(s.get('target_pct', 0)):.0f}%",
                detail=f"{len(funds)} fund(s) selected",
            ))
        else:
            findings.append(InsightFinding(
                priority="high",
                title=f"{s.get('label', 'Sleeve')} · {float(s.get('target_pct', 0)):.0f}%",
                detail=f"No eligible fund — {_empty_sleeve_reason(s)}",
            ))

    recommendation = InsightRecommendation(
        summary=(
            f"Proposed {str(profile).title()} portfolio across "
            f"{len([s for s in sleeves if s.get('funds')])} populated sleeve(s)."
        ),
        rationale=verdict,
    )

    card = InsightCardData(
        hero=hero,
        kpis=kpis,
        findings=findings,
        recommendation=recommendation,
    )
    return _envelope("Proposed portfolio", card,
                     suggestions=["Why these funds?", "Show overlap detail"])


def _empty_sleeve_reason(sleeve: Dict[str, Any]) -> str:
    """Best honest reason a sleeve has no funds, read from the selection block.

    Prefers the most specific recorded rejection reason; falls back to a
    generic 'no eligible candidates' rather than implying success.
    """
    sel = sleeve.get("selection") or {}
    rejected = sel.get("rejected") or []
    reasons: List[str] = []
    for r in rejected:
        gr = r.get("gate_reason")
        if gr:
            reasons.append(str(gr))
        elif r.get("overlap_status") == "rejected":
            reasons.append("rejected for holdings overlap")
    if reasons:
        # Surface up to two distinct reasons.
        seen: List[str] = []
        for x in reasons:
            if x not in seen:
                seen.append(x)
        return "; ".join(seen[:2])
    if sel.get("shortlist_size") == 0:
        return "no candidates returned for this category"
    return "no eligible candidates after gates"


def _sleeve_card(sleeve: Dict[str, Any]) -> Dict[str, Any]:
    """One card per non-empty sleeve, listing each pick with score + gate chips
    + overlap note as STRUCTURED fields (never inside a free-text string)."""
    label = sleeve.get("label", "Sleeve")
    funds = sleeve.get("funds") or []
    target_pct = float(sleeve.get("target_pct", 0) or 0)

    # Hero severity = worst gate severity across the sleeve's picks, so a
    # not_evaluated/failed gate is visible at the sleeve level too.
    worst: InsightSeverity = "healthy"
    rank = {"healthy": 0, "medium": 1, "high": 2, "critical": 3, "info": 0}
    for f in funds:
        gs = _gate_summary(f.get("gate_results"))
        if rank.get(gs["worst_severity"], 0) > rank.get(worst, 0):
            worst = gs["worst_severity"]

    hero = InsightHero(
        severity=worst,
        eyebrow=f"Sleeve · {target_pct:.0f}%",
        headline=label,
        primary_value=str(len(funds)),
        primary_label="fund(s)",
        subtitle=sleeve.get("detail"),
    )

    # KPIs: one per pick — name + score, structured (no narration).
    kpis: List[InsightKpi] = []
    for f in funds[:4]:
        score = _fund_score(f)
        kpis.append(InsightKpi(
            label=_fund_name(f)[:30],
            value=(f"{score:.0f}" if score is not None else "—"),
            sublabel="score",
        ))

    # Findings: one per pick carrying the gate chips + overlap note. Gate chips
    # are passed through as structured data on each finding's detail, with the
    # worst gate severity driving the finding priority and tone.
    findings: List[InsightFinding] = []
    for f in funds:
        gs = _gate_summary(f.get("gate_results"))
        chip_bits = []
        for c in gs["chips"]:
            chip_bits.append(f"{c['gate']}: {_GATE_VERB[c['status']]}")
        overlap = _overlap_note(f)
        detail_parts = []
        if chip_bits:
            detail_parts.append(" · ".join(chip_bits))
        detail_parts.append(overlap)
        score = _fund_score(f)
        findings.append(InsightFinding(
            priority=_priority_from_severity(gs["worst_severity"]),
            title=_fund_name(f),
            detail=" — ".join(detail_parts),
            impact_value=(f"{score:.0f}" if score is not None else None),
            impact_label="score",
        ))

    # Recommendation is narration-only; it must NOT contain pick names/scores
    # (those live in the structured findings above).
    n_ne = sum(_gate_summary(f.get("gate_results"))["not_evaluated"] for f in funds)
    n_failed = sum(_gate_summary(f.get("gate_results"))["failed"] for f in funds)
    rec_bits = [f"{len(funds)} fund(s) selected for this sleeve."]
    if n_failed:
        rec_bits.append(f"{n_failed} gate(s) failed — review flagged picks.")
    if n_ne:
        rec_bits.append(
            f"{n_ne} gate(s) could not be evaluated (shown amber, not as a pass)."
        )
    recommendation = InsightRecommendation(summary=" ".join(rec_bits))

    card = InsightCardData(
        hero=hero,
        kpis=kpis,
        findings=findings,
        recommendation=recommendation,
    )
    return _envelope(label, card)


def _empty_sleeve_card(sleeve: Dict[str, Any]) -> Dict[str, Any]:
    """Explicit card for a sleeve that ended up with no funds after gates.

    Never silently dropped — the reason is surfaced as the headline.
    """
    label = sleeve.get("label", "Sleeve")
    target_pct = float(sleeve.get("target_pct", 0) or 0)
    reason = _empty_sleeve_reason(sleeve)

    hero = InsightHero(
        severity="high",
        eyebrow=f"Sleeve · {target_pct:.0f}%",
        headline=f"{label}: no eligible fund",
        primary_value="0",
        primary_label="fund(s)",
        subtitle=reason,
    )

    # Surface the actual rejected candidates (if any) as structured findings so
    # the user can see WHAT was rejected and WHY.
    findings: List[InsightFinding] = []
    sel = sleeve.get("selection") or {}
    for r in (sel.get("rejected") or [])[:4]:
        name = _fund_name(r)
        if r.get("gate_reason"):
            why = str(r.get("gate_reason"))
        elif r.get("overlap_status") == "rejected":
            pct = r.get("overlap_pct")
            why = (f"overlap too high ({float(pct) * 100:.0f}%)"
                   if pct is not None else "overlap too high")
        else:
            why = "rejected"
        findings.append(InsightFinding(priority="high", title=name, detail=why))

    recommendation = InsightRecommendation(
        summary=f"No fund qualified for {label}. {reason}",
    )

    card = InsightCardData(
        hero=hero,
        findings=findings,
        recommendation=recommendation,
    )
    return _envelope(f"{label} — no eligible fund", card)


# ── Mandatory disclosures card (both modes) ─────────────────────────────────

def _disclosures_card() -> Dict[str, Any]:
    """Non-dismissible disclosures block attached to every result."""
    hero = InsightHero(
        severity="info",
        eyebrow="Disclosures",
        headline="Important disclosures",
        subtitle="Please read before acting on this proposal.",
    )
    findings = [
        InsightFinding(priority="medium", title=d) for d in DISCLOSURES
    ]
    education = InsightEducation(
        heading="Regulatory note",
        body=(
            "These disclosures are mandatory and cannot be dismissed. They "
            "accompany every model-driven proposal."
        ),
    )
    card = InsightCardData(hero=hero, findings=findings, education=education)
    return _envelope("Disclosures", card)


# ── Public entry point ──────────────────────────────────────────────────────

def _is_named_mode(builder_output: Dict[str, Any]) -> bool:
    """Named mode requires BOTH: compliance allows names AND at least one
    sleeve actually has a named fund. Either condition failing -> category mode.
    """
    compliance = builder_output.get("compliance") or {}
    if not compliance.get("names_allowed"):
        return False
    sleeves = builder_output.get("sleeves") or []
    return any((s.get("funds") or []) for s in sleeves)


def portfolio_result_to_cards(builder_output: Dict[str, Any]) -> List[Dict[str, Any]]:
    """Transform a `sleeve_builder.build_sleeve_portfolio` result into a list
    of insight_card envelope dicts ready for the chat dispatcher.

    - Category / model mode: a single guidance card (NO scheme names) +
      mandatory disclosures.
    - Named mode: a header card + one card per sleeve (empty sleeves surfaced
      explicitly with their reason) + mandatory disclosures.

    The disclosures card is always last and always present.
    """
    if not isinstance(builder_output, dict):
        # Defensive: a malformed input still yields a well-formed disclosures
        # card rather than crashing the chat renderer.
        return [_disclosures_card()]

    cards: List[Dict[str, Any]] = []

    if not _is_named_mode(builder_output):
        cards.append(_category_card(builder_output))
        cards.append(_disclosures_card())
        return cards

    # Named mode.
    cards.append(_header_card(builder_output))
    for s in builder_output.get("sleeves") or []:
        funds = s.get("funds") or []
        if funds:
            cards.append(_sleeve_card(s))
        else:
            # Only surface an empty-sleeve card for sleeves that have a real
            # allocation target (a 0% sleeve was never built).
            if float(s.get("target_pct", 0) or 0) > 0:
                cards.append(_empty_sleeve_card(s))
    cards.append(_disclosures_card())
    return cards
