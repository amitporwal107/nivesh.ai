def test_values_equal_the_daily_indicators_on_the_same_candles_ragged():
    days = sessions(date(2026, 11, 3), 5)
    data = {"AAA": make_bars(days, 15, 1), "BBB": make_bars(days[-2:], 15, 2), "CCC": make_bars(days[-1:], 15, 3)[:10]}
    got = iv.compute(data, NEEDS)
    a, k = right_aligned([data["AAA"], data["BBB"], data["CCC"]])
    dip, dim, adx = I.dmi(a["high"], a["low"], a["close"], 14)
    st = I.supertrend(a["high"], a["low"], a["close"], 7, 3.0)
    rng = a["high"] - a["low"]
    expect = {
        "ema21": I.ema(a["close"], 21)[k - 1], "ema21_1": I.ema(a["close"], 21)[k - 2], "smav5": I.sma(a["volume"], 5)[k - 1],
        "rsi14": I.rsi(a["close"], 14)[k - 1], "adx": adx[k - 1], "dip": dip[k - 1], "dim": dim[k - 1],
        "st0": st[k - 1], "st1": st[k - 2], "c1": a["close"][k - 2],
        "cir": ((a["close"] - a["low"]) / rng * 100.0)[k - 1],
    }
    for j, s in enumerate(("AAA", "BBB", "CCC")):
        for key, arr in expect.items():
            want = float(arr[j]) if np.isfinite(arr[j]) else None
            assert same(got[s][key], want), (s, key, got[s][key], want)
    # CCC has 10 candles: EMA(21) and ADX(14) need more, so they are missing rather than invented
    assert got["CCC"]["ema21"] is None and got["CCC"]["adx"] is None
    assert got["AAA"]["ema21"] is not None and got["AAA"]["adx"] is not None


def test_first_high_is_the_high_of_the_latest_sessions_first_candle_whatever_the_offset():
    days = sessions(date(2026, 11, 3), 2)
