def run(coro):
    return asyncio.run(coro)


class Clock:
    """Fake wall clock; sleep moves it forward."""

    def __init__(self, at: datetime):
        self.t = at.timestamp()

    def wall(self) -> float:
        return self.t

    def now(self) -> datetime:
        return datetime.fromtimestamp(self.t, timezone.utc)

    async def sleep(self, d: float) -> None:
        self.t += max(0.0, d)
        await asyncio.sleep(0)


def sessions(last: date, n: int):
    out, d = [], last
    while len(out) < n:
        if d.weekday() < 5:
            out.append(d)
        d -= timedelta(days=1)
    return sorted(out)


def make_bars(days, minutes: int, seed: int, start: float = 100.0, last_day_upto: datetime = None):
    """Seeded candles 09:15 onward each day; on the last day only those started at or before `last_day_upto`."""
    rng = np.random.RandomState(seed)
    price = start
    bars = []
    per_day = math.ceil(375 / minutes)
    for d in days:
        for i in range(per_day):
            t = datetime(d.year, d.month, d.day, 9, 15, tzinfo=IST) + timedelta(minutes=minutes * i)
            if last_day_upto is not None and d == days[-1] and t > last_day_upto:
                break
            o = price
            c = max(1.0, o * (1 + rng.normal(0, 0.004)))
            h = max(o, c) * (1 + abs(rng.normal(0, 0.002)))
            l = min(o, c) * (1 - abs(rng.normal(0, 0.002)))
            v = float(rng.randint(1000, 50000))
            bars.append([t.isoformat(), o, h, l, c, v])
            price = c
    return bars


class FakeFetcher:
    """Stands in for KiteFetcher: answers from `data`, records (symbol, interval key, sessions, fake time)."""

    def __init__(self, data, clock=None, log=None, fail=(), availability=None, gate: asyncio.Event = None):
        self.data, self.clock, self.fail = data, clock, set(fail)
        self.availability = availability or {}
        self.log = log if log is not None else []
        self.gate = gate

    async def bars(self, symbol, interval_key, sessions):
        self.log.append((symbol, interval_key, sessions, self.clock.wall() if self.clock else None))
        if self.gate is not None:
            await self.gate.wait()
        if symbol in self.fail:
            raise RuntimeError("upstream_unavailable")
        if symbol in self.availability:
            return {"availability": self.availability[symbol], "bars": []}
        b = self.data.get(symbol)
        if b is None:
            return {"availability": "symbol_not_found", "bars": []}
        return {"availability": "ok" if b else "no_bars", "bars": [list(x) for x in b]}


