def test_kite_calls_are_spaced_across_workers_at_most_one_and_a_half_per_second():
    async def go():
        clock = Clock(OPEN_1005)
        syms = [f"S{i}" for i in range(12)]
        data = _open_data(symbols=syms)
        store = iv.LocalStore(clock.wall)
        log = []
        workers = [service(clock, FakeFetcher(data, clock, log), store) for _ in range(3)]
        for i, s in enumerate(syms):                      # the workers take turns, as uvicorn's would
            await workers[i % 3]._refresh_one(iv._ckey("15minute", 5, s), s, "15minute", 5)
        times = [x[3] for x in log]
        assert len(times) == 12
        assert all(b - a >= iv.SPACING_S - 1e-9 for a, b in zip(times, times[1:]))
        assert max(sum(1 for u in times if t <= u < t + 1.0) for t in times) <= 2     # ≤ 1.5 per second
        assert max(sum(1 for u in times if t <= u < t + 10.0) for t in times) <= 15
        return True
    assert run(go())


