def test_never_read_15_minute_candles_go_before_a_one_hour_backlog():
    # Staging 3 Nov 09:39: after a restart the 218-stock 1-hour backlog (≈2.5 min at 1.5 calls/s) held up the few 15-minute
    # reads the Nifty 50 / Supertrend / strong-mover widgets needed. Ties among never-read candles now go to 15 minutes.
    async def go():
        clock = Clock(OPEN_1005)
        hourly = [f"H{i}" for i in range(6)]
        data = _open_data(symbols=tuple(hourly) + ("Q1", "Q2"))
        gate = asyncio.Event()
        f = FakeFetcher(data, clock, gate=gate)
        svc = service(clock, f, first_wait=0.0)
        await svc.values(hourly, "60minute", NEEDS, lookback_days=20)      # the backlog: H0 starts, H1..H5 wait
        await asyncio.sleep(0)
        await svc.values(["Q1", "Q2"], "15minute", NEEDS, lookback_days=5)   # asked while H0 is being read
        gate.set()
        await svc._task
        order = [x[0] for x in f.log]
        assert order[0] == "H0" and order[1:3] == ["Q1", "Q2"] and sorted(order[3:]) == hourly[1:]
        return True
    assert run(go())
