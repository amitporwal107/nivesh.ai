def right_aligned(series_list):
    k = max(len(s) for s in series_list)
    out = {f: np.full((k, len(series_list)), np.nan) for f in ("open", "high", "low", "close", "volume")}
    for j, bars in enumerate(series_list):
        m = np.asarray([b[1:6] for b in bars], dtype=float)
        for i, f in enumerate(("open", "high", "low", "close", "volume")):
            out[f][k - len(bars):, j] = m[:, i]
    return out, k


def same(a, b, tol=1e-9):
    if a is None or b is None:
        return a is None and b is None
    return abs(a - b) <= tol * max(1.0, abs(b))


