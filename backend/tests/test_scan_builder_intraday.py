def _open_data(clock_at=OPEN_1005, minutes=15, n_sessions=5, symbols=("AAA", "BBB", "CCC")):
    days = sessions(clock_at.date(), n_sessions)
    return {s: make_bars(days, minutes, 10 + i, last_day_upto=clock_at) for i, s in enumerate(symbols)}


def test_first_call_reads_kite_then_answers_from_cache_while_fresh():
    async def go():
        clock = Clock(OPEN_1005)
        data = _open_data()
        f = FakeFetcher(data, clock)
        svc = service(clock, f)
        r1 = await svc.values(["AAA", "BBB", "CCC"], "15minute", NEEDS, lookback_days=5)
        assert sorted(x[0] for x in f.log) == ["AAA", "BBB", "CCC"] and all(x[1:3] == ("15m", 5) for x in f.log)
        assert r1.missing == [] and r1.values["AAA"]["ema21"] is not None
        assert r1.as_of == "2026-11-03T10:00:00+05:30"        # the candle in progress at 10:05
        clock.t += 30                                         # 15-minute candles stay fresh for 60 s in the session
        r2 = await svc.values(["AAA", "BBB", "CCC"], "15minute", NEEDS, lookback_days=5)
        assert len(f.log) == 3 and r2.values == r1.values
        return True
    assert run(go())


